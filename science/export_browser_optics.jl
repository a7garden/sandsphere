using SpeedyWeather, NumericalRadiation, JSON3, SHA, Random, Base64
const NR=NumericalRadiation
const NAMES=(:composite,:h2o,:o3,:co2,:ch4,:n2o,:cfc11,:cfc12)
g=NR.read_reference_ecckd_gas_optics("32x32";names=NAMES)
fields=Dict(string(n)=>(shape=collect(size(getproperty(g,n))),data=base64encode(reinterpret(UInt8,vec(Float32.(getproperty(g,n)))))) for n in propertynames(g) if getproperty(g,n) isa AbstractArray)
source=NR.reference_ecckd_definition_paths("32x32")
liquid=NR.read_cloud_scattering_table(NR.ecrad_data_file("mie_droplet_scattering.nc"))
ice=NR.read_cloud_scattering_table(NR.ecrad_data_file("baum-general-habit-mixture_ice_scattering.nc"))
cloud=Dict{String,Any}()
for (name,table,radius) in (("liquid",liquid,10e-6),("ice",ice,30e-6))
 for (wave,path) in (("Longwave",source.longwave),("Shortwave",source.shortwave))
  optics=NR.SpectralCloudOptics(Float64,table,NR.read_ecckd_spectral_mapping(path);effective_radius=radius)
  cloud[name*wave*"Absorption"]=vec(optics.mass_extinction_coefficient[:,1].*(1 .- optics.single_scattering_albedo[:,1]))
  cloud[name*wave*"Transport"]=vec(optics.mass_extinction_coefficient[:,1].*optics.single_scattering_albedo[:,1].*(1 .- optics.asymmetry_factor[:,1]))
 end
end
metadata=(schema=1,source="ecCKD 32x32 via NumericalRadiation 0.1.1",gasNames=NAMES,
  sourceSha256=(longwave=bytes2hex(sha256(read(source.longwave))),shortwave=bytes2hex(sha256(read(source.shortwave)))),
  arrayOrder="Little-endian Float32, Julia column-major; g-point varies fastest",license="Apache-2.0",fields,cloud)
mkpath("src/sim/data")
open("src/sim/data/ecckd-32.json","w") do io;JSON3.write(io,metadata);end
# Independent scalar optics/source fixtures, including cold upper-air and
# off-table edges. These are generated by Julia, not by the TypeScript port.
Random.seed!(82026);rows=[]
for i in 1:64
 p=exp(log(.01)+rand()*(log(150000)-log(.01)));T=110+rand()*300;h=exp(log(1e-12)+rand()*(log(.1)-log(1e-12)))
 dry=rand()*30000;water=h*dry;co2=rand()*1500e-6;ch4=rand()*10e-6;o3=NR.default_ozone_profile(p)
 gases=(composite=dry,h2o=water,o3=o3*dry,co2=co2*dry,ch4=ch4*dry,n2o=320e-9*dry,cfc11=0.,cfc12=0.)
 stencil=NR.gas_optics_stencil(g,p,T,h);sb=NR.source_table_bracket(g,T)
 push!(rows,(pressure=p,temperature=T,dryMoles=dry,waterMoles=water,co2,ch4,o3,
  longwave=[NR.longwave_optical_depth(g,k,gases,stencil) for k in 1:32],
  shortwave=[NR.shortwave_optical_depth(g,k,gases,stencil) for k in 1:32],
  source=[NR.longwave_source(g,k,T,sb) for k in 1:32]))
end
open("tests/fixtures/ecckd-optics-reference.json","w") do io;JSON3.write(io,(source=metadata.source,sourceSha256=metadata.sourceSha256,rows));end
println("Exported original ecCKD tables and 64 independent optics fixtures")

# Forward layer sources are generated by NumericalRadiation's own solver.
transfer=[]
for depth in (.002,.01,.1,1.,10.,100.), (top,bottom) in ((190.,290.),(290.,190.),(230.,230.))
    a=NR.longwave_source(g,1,top,NR.source_table_bracket(g,top))
    b=NR.longwave_source(g,1,bottom,NR.source_table_bracket(g,bottom))
    trans,up,down=NR.no_scattering_longwave_sources(Float64,depth,a,b)
    push!(transfer,(depth,topSource=a,bottomSource=b,transmission=trans,upwardSource=up,downwardSource=down))
end
open("tests/fixtures/ecckd-transfer-reference.json","w") do io;JSON3.write(io,(source="NumericalRadiation 0.1.1 no_scattering_longwave_sources",transfer));end
